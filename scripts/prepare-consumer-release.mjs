#!/usr/bin/env node

import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, join, resolve } from "node:path";
import { validateTraceCCPackageRuntimeDirectory } from "./prepare-package-runtime.mjs";

const root = join(import.meta.dirname, "..");
const sourceManifest = JSON.parse(
  readFileSync(join(root, "toolchain", "manifest.json"), "utf8"),
);
const releaseDirectory = process.env.TRACECC_TOOLCHAIN_RELEASE_DIR;
const pchDirectory = process.env.TRACECC_PCH_DIR;
const runtimeHeader = resolve(
  process.env.TRACECC_RUNTIME_HEADER ??
    join(root, "runtime", "tracecode_runtime.hpp"),
);
const outputRoot = resolve(
  process.env.TRACECC_CONSUMER_RELEASE_ROOT ??
    join(root, ".cache", "consumer-releases"),
);
const TRACECC_CONSUMER_RELEASE_FORMAT = "tracecc-consumer-release-v2";
const TRACECC_CONSUMER_HASH_ALGORITHM =
  "sha256-canonical-json-tracecc-consumer-release-v2";
const TRACECC_CONSUMER_LOCK_SCHEMA = "tracecc-consumer-lock-v2";
const TRACECC_RUNTIME_MANIFEST_SCHEMA = "tracecc-runtime-assets-v2";

if (!releaseDirectory || !pchDirectory) {
  throw new Error(
    "TRACECC_TOOLCHAIN_RELEASE_DIR and TRACECC_PCH_DIR are required.",
  );
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function integrity(digest) {
  return `sha256-${Buffer.from(digest, "hex").toString("base64")}`;
}

function identity(source, path, mediaType) {
  const absolute = resolve(source);
  const metadata = lstatSync(absolute);
  if (!metadata.isFile() || metadata.isSymbolicLink()) {
    throw new Error(`TraceCC consumer input must be a regular file: ${absolute}`);
  }
  const bytes = readFileSync(absolute);
  const digest = sha256(bytes);
  return {
    source: absolute,
    path,
    size: bytes.byteLength,
    sha256: digest,
    integrity: integrity(digest),
    mediaType,
  };
}

function readMetadata(source, label) {
  const absolute = resolve(source);
  const metadata = lstatSync(absolute);
  if (!metadata.isFile() || metadata.isSymbolicLink()) {
    throw new Error(`TraceCC ${label} must be a regular file: ${absolute}`);
  }
  try {
    return JSON.parse(readFileSync(absolute, "utf8"));
  } catch (error) {
    throw new Error(`TraceCC ${label} is not valid JSON: ${absolute}`, {
      cause: error,
    });
  }
}

function assertProfileProvenance(
  profile,
  pch,
  source,
  object,
  header,
  expectedAnchors,
) {
  const pchMetadata = readMetadata(
    join(pchRoot, `${profile}.pch.json`),
    `${profile} PCH provenance`,
  );
  const objectMetadata = readMetadata(
    join(pchRoot, `${profile}.o.json`),
    `${profile} runtime-object provenance`,
  );
  const trustedCompiler = sourceManifest.buildInputs?.pchCompiler;
  const expectedFlags = [
    "-O0",
    "-fno-exceptions",
    "-fpch-instantiate-templates",
    "-fpch-codegen",
  ];
  const pchMatches =
    pchMetadata.compilerVersion === trustedCompiler?.version &&
    pchMetadata.compilerSha256 === trustedCompiler?.wasmSha256 &&
    pchMetadata.compilerBundleSha256 === trustedCompiler?.bundleSha256 &&
    pchMetadata.runtimeHeaderSha256 === header.sha256 &&
    pchMetadata.pchSourceSha256 === source.sha256 &&
    pchMetadata.languageStandard === "c++23" &&
    JSON.stringify(pchMetadata.flags) === JSON.stringify(expectedFlags) &&
    pchMetadata.instantiateTemplates === true &&
    pchMetadata.commonTypeAnchors === expectedAnchors.common &&
    pchMetadata.corpusTypeAnchors === expectedAnchors.corpus &&
    pchMetadata.mapTypeAnchors === expectedAnchors.map &&
    pchMetadata.bytes === pch.size &&
    pchMetadata.sha256 === pch.sha256;
  const objectMatches =
    objectMetadata.compilerVersion === trustedCompiler?.version &&
    objectMetadata.compilerSha256 === trustedCompiler?.wasmSha256 &&
    objectMetadata.compilerBundleSha256 === trustedCompiler?.bundleSha256 &&
    objectMetadata.runtimeHeaderSha256 === header.sha256 &&
    objectMetadata.pchSourceSha256 === source.sha256 &&
    objectMetadata.pchSha256 === pch.sha256 &&
    objectMetadata.bytes === object.size &&
    objectMetadata.sha256 === object.sha256;
  if (!pchMatches || !objectMatches) {
    throw new Error(
      `TraceCC ${profile} PCH/runtime-object provenance does not match the pinned compiler, runtime header, profile, and generated bytes.`,
    );
  }
}

function descriptor(file) {
  return {
    url: file.path,
    integrity: file.integrity,
    mediaType: file.mediaType,
    size: file.size,
    delivery: { mutability: "immutable", address: "content" },
  };
}

function verifyToolchainRelease(directory) {
  const result = spawnSync(
    process.execPath,
    [join(root, "scripts", "verify-toolchain-release.mjs")],
    {
      cwd: root,
      env: { ...process.env, TRACECC_RELEASE_DIR: directory },
      encoding: "utf8",
    },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(
      result.stderr || result.stdout || "TraceCC toolchain verification failed.",
    );
  }
}

const releaseRoot = resolve(releaseDirectory);
verifyToolchainRelease(releaseRoot);
const release = JSON.parse(
  readFileSync(join(releaseRoot, "release.json"), "utf8"),
);
const pchRoot = resolve(pchDirectory);
const reactor = identity(
  join(releaseRoot, release.artifacts.reactor.path),
  "tracecc-reactor.wasm",
  "application/wasm",
);
const resources = identity(
  join(releaseRoot, release.artifacts.resources.path),
  "llvm-resources.tar",
  "application/x-tar",
);
const header = identity(runtimeHeader, "tracecode_runtime.hpp", "text/plain");

function profileFiles(profile, expectedAnchors) {
  const pch = identity(
    join(pchRoot, `${profile}.pch`),
    `${profile}.pch`,
    "application/octet-stream",
  );
  const source = identity(
    join(pchRoot, `${profile}.pch.source.hpp`),
    `${profile}.source.hpp`,
    "text/plain",
  );
  const object = identity(
    join(pchRoot, `${profile}.o`),
    `${profile}.o`,
    "application/wasm",
  );
  assertProfileProvenance(
    profile,
    pch,
    source,
    object,
    header,
    expectedAnchors,
  );
  return [pch, source, object];
}

const files = [
  reactor,
  resources,
  header,
  ...profileFiles("narrow", { common: true, corpus: false, map: false }),
  ...profileFiles("broad", { common: false, corpus: true, map: false }),
  ...profileFiles("map", { common: false, corpus: false, map: true }),
];

if (
  reactor.sha256 !== release.artifacts.reactor.sha256 ||
  resources.sha256 !== release.artifacts.resources.sha256 ||
  reactor.sha256 !== sourceManifest.candidate?.foldedSha256 ||
  resources.sha256 !== sourceManifest.buildInputs?.runtimeResources?.sha256 ||
  resources.sha256 !==
    sourceManifest.buildInputs?.pchCompiler?.resourcesSha256
) {
  throw new Error("Verified toolchain descriptor does not match its consumer inputs.");
}

const consumerHash = sha256(
  Buffer.from(
    JSON.stringify({
      format: TRACECC_CONSUMER_RELEASE_FORMAT,
      toolchainContentHash: release.contentHash,
      files: files.map(({ path, size, sha256: digest, mediaType }) => ({
        path,
        size,
        sha256: digest,
        mediaType,
      })),
    }),
  ),
);
const lock = {
  schema: TRACECC_CONSUMER_LOCK_SCHEMA,
  consumerHash,
  consumerHashAlgorithm: TRACECC_CONSUMER_HASH_ALGORITHM,
  toolchain: {
    protocolVersion: release.protocolVersion,
    contentHash: release.contentHash,
    artifacts: {
      reactor: {
        path: files[0].path,
        bytes: files[0].size,
        sha256: files[0].sha256,
        integrity: files[0].integrity,
        mediaType: files[0].mediaType,
      },
      resources: {
        path: files[1].path,
        bytes: files[1].size,
        sha256: files[1].sha256,
        integrity: files[1].integrity,
        mediaType: files[1].mediaType,
      },
    },
  },
  files: files.map(
    ({ path, size, sha256: digest, integrity: sri, mediaType }) => ({
      path,
      size,
      sha256: digest,
      integrity: sri,
      mediaType,
    }),
  ),
};
const [
  ,
  ,
  ,
  narrowPch,
  narrowSource,
  narrowObject,
  broadPch,
  broadSource,
  broadObject,
  mapPch,
  mapSource,
  mapObject,
] = files;
const manifest = {
  schema: TRACECC_RUNTIME_MANIFEST_SCHEMA,
  runtime: "tracecc",
  runtimeVersion: `tracecc-${consumerHash.slice(0, 12)}`,
  contentHash: consumerHash,
  assets: {
    runtimeHeader: descriptor(header),
    compilerWasm: descriptor(reactor),
    linkerWasm: descriptor(reactor),
    sysroot: descriptor(resources),
    compilerResources: {
      "tracecc-narrow-pch": descriptor(narrowPch),
      "tracecc-narrow-pch-source": descriptor(narrowSource),
      "tracecc-narrow-runtime-object": descriptor(narrowObject),
      "tracecc-broad-pch": descriptor(broadPch),
      "tracecc-broad-pch-source": descriptor(broadSource),
      "tracecc-broad-runtime-object": descriptor(broadObject),
      "tracecc-map-pch": descriptor(mapPch),
      "tracecc-map-pch-source": descriptor(mapSource),
      "tracecc-map-runtime-object": descriptor(mapObject),
    },
  },
};

mkdirSync(outputRoot, { recursive: true });
const staging = join(outputRoot, `.${consumerHash}.stage-${process.pid}`);
const outputDirectory = join(outputRoot, consumerHash);
rmSync(staging, { recursive: true, force: true });
mkdirSync(staging, { recursive: true });
for (const file of files) copyFileSync(file.source, join(staging, file.path));
writeFileSync(
  join(staging, "tracecc-consumer-lock.json"),
  `${JSON.stringify(lock, null, 2)}\n`,
);
writeFileSync(
  join(staging, "tracecc-runtime-manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
);
validateTraceCCPackageRuntimeDirectory(staging, {
  expectedDirectoryName: false,
});
rmSync(outputDirectory, { recursive: true, force: true });
renameSync(staging, outputDirectory);

console.log(
  JSON.stringify(
    {
      outputDirectory,
      consumerHash,
      toolchainContentHash: release.contentHash,
      fileCount: files.length,
      bytes: files.reduce((total, file) => total + file.size, 0),
      runtimeHeader: basename(runtimeHeader),
    },
    null,
    2,
  ),
);
